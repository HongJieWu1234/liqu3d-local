import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Navigation only: named function declarations, not a JavaScript parser/API extractor.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const paths = ['server.mjs', 'renderer-service.mjs', 'renderer-worker.mjs'];
for (const dir of ['lib', 'public', 'scripts']) {
  for (const entry of await fs.readdir(path.join(root, dir), { withFileTypes: true })) {
    if (entry.isFile() && /\.(?:mjs|js)$/.test(entry.name)) paths.push(`${dir}/${entry.name}`);
  }
}
const sections = [];
let count = 0;
for (const file of paths.sort()) {
  const source = await fs.readFile(path.join(root, file), 'utf8');
  const entries = [];
  source.split('\n').forEach((line, index) => {
    const match = line.match(/^\s*(?:export\s+)?(?:async\s+)?function\s+([\w$]+)\s*\(/);
    if (match) entries.push(`| \`${match[1]}\` | ${index + 1} |`);
  });
  count += entries.length;
  sections.push(`## ${file}\n\n[Open source](../${file})\n\n${entries.length ? '| Named declaration | Source line |\n| --- | --- |\n' + entries.join('\n') : 'No named function declarations matched; see source for module initialization, classes, arrow functions or message handlers.'}\n`);
}
const output = `# Named-function source index\n\n[Documentation home](README.md) · [Function behavior and contracts](FUNCTION_REFERENCE.md)\n\nGenerated by \`node scripts/document-functions.mjs\`. Covers ${paths.length} first-party runtime/tool JavaScript files and ${count} named function declarations. Scans root entrypoints and direct files in \`lib/\`, \`public/\` and \`scripts/\`; excludes vendor code and tests. Includes nested named declarations. This line-based navigation index does not parse JavaScript: anonymous callbacks, arrow functions, class/object methods and unconventional multiline declaration headers are outside its coverage. Line numbers reflect the last generation; linked source is authoritative. Read the function reference for explanations rather than inferring behavior from names.\n\n${sections.join('\n')}`;
await fs.writeFile(path.join(root, 'docs/SOURCE_INDEX.md'), output);
console.log(`Documented ${count} named declarations across ${paths.length} files.`);
