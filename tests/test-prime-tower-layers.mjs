import './setup.mjs';
import assert from 'node:assert/strict';
import { BoxGeometry,Mesh,MeshBasicMaterial } from '../public/vendor/three/three.module.js';
import { estimatePrimeTower,normalizePrimeTowerSettings } from '../public/prime-tower.js';
import { analyzeWorkspaceTowerMeshes } from '../public/workspace-tower-analysis.js';
import { summarizeTowerLayers } from '../public/prime-tower-layers.js';
import { estimatePrintWaste } from '../public/purge-estimate.js';
import { migratePrintSettings } from '../public/print-settings-schema.js';
const palette=['#FF0000','#0000FF','#00FF00','#FFFFFF'];
const item=runs=>({height:20,towerChannels:palette,colorAnalysis:{status:'ready',channels:palette.map(color=>({color,id:color})),layerHeight:.2,firstLayerHeight:.2,runs}});
const config={enable_prime_tower:true,prime_tower_rib_wall:false,prime_tower_width:35,layer_height:.2,filament_colour:palette};
const together=[{from:1,to:100,colors:palette}];
const stacked=palette.map((color,i)=>({from:1+i*25,to:(i+1)*25,colors:[color]}));
const full=estimatePrimeTower([item(together)],config),sequential=estimatePrimeTower([item(stacked)],config);
assert.ok(full.depth>sequential.depth,'Colors sharing a layer need more tower area than the same colors at separate heights');
const bottom=[{from:1,to:5,colors:palette},{from:6,to:100,colors:[palette[0]]}];
const short=estimatePrimeTower([item(bottom)],config);
assert.equal(short.lastChangeLayer,6);assert.ok(short.height<2,'Tower ends at the final transition, not the model top');
const skipped=estimatePrimeTower([item(stacked)],{...config,wipe_tower_no_sparse_layers:true});
assert.equal(skipped.printedLayerCount,4);assert.equal(skipped.height,.8);
assert.ok(skipped.height<sequential.height);
assert.equal(estimatePrimeTower([item(together)],{...config,enable_prime_tower:false}),null);
const heavier=estimatePrimeTower([item(together)],{...config,filament_prime_volume:90});
assert.ok(heavier.depth>full.depth,'Priming settings affect required area');
const first=estimatePrimeTower([item([{from:1,to:1,colors:palette},{from:2,to:100,colors:[palette.at(-1)]}])],config);
assert.ok(first.height<1);
const wasted=estimatePrintWaste(bottom,palette,config,[item(bottom)]);
const trimmed=estimatePrintWaste(bottom.map(run=>({...run,to:Math.min(run.to,short.lastChangeLayer)})),palette,config,[item(bottom)]);
assert.ok(Math.abs(wasted.towerGrams-trimmed.towerGrams)<1e-8,'Single-color layers above the last switch add no tower waste');
// Large runs use cycle skipping, while matching a layer-by-layer reference.
const settings=normalizePrimeTowerSettings(config),long=[{from:1,to:99999,colors:palette}];
assert.equal(summarizeTowerLayers(long,settings).printedLayerCount,99999);
const split=Array.from({length:60},(_,i)=>({from:i+1,to:i+1,colors:palette}));
const compressed=summarizeTowerLayers([{from:1,to:60,colors:palette}],settings),expanded=summarizeTowerLayers(split,settings);
for(const key of ['height','primeArea','lastChangeLayer','printedLayerCount'])assert.equal(compressed[key],expanded[key]);
const mesh=(color,z,height)=>{
 const m=new Mesh(new BoxGeometry(10,10,height).translate(0,0,z+height/2),new MeshBasicMaterial());
 m.rotation.x=-Math.PI/2;m.userData.hexColor=color;return m;
};
const meshes=[mesh(palette[0],0,1),mesh(palette[1],1,1)];
const analysis=analyzeWorkspaceTowerMeshes(meshes,{layerHeight:.2});
assert.equal(analysis.status,'ready');assert.deepEqual(analysis.runs.map(run=>[run.from,run.to,run.colors.length]),[[1,5,1],[6,10,1]]);
assert.equal(analyzeWorkspaceTowerMeshes(meshes,{layerHeight:.2}),analysis,'Unchanged meshes reuse layer analysis');
const actual=estimatePrimeTower([{height:2,towerChannels:palette.slice(0,2),colorAnalysis:analysis}],config);
assert.equal(actual.lastChangeLayer,6);assert.ok(Math.abs(actual.height-1.2)<1e-8);
for(const m of meshes){m.geometry.dispose();m.material.dispose();}
assert.equal(migratePrintSettings({enable_prime_tower:'0'}).enable_prime_tower,false);
assert.equal(migratePrintSettings({enable_prime_tower:['1']}).enable_prime_tower,true);
console.log('Layer-aware towers passed: concurrent colors, last change, skipped layers, priming demand, waste cutoff, long-run cycles, generated meshes, caching and imported toggles.');
