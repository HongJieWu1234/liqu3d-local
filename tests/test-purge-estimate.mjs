import './setup.mjs';
import assert from 'node:assert/strict';
import { estimatePrintWaste } from '../public/purge-estimate.js';
import { estimatePrimeTower } from '../public/prime-tower.js';
import { estimateFilament } from '../public/filament-estimate.js';
import { exportedPrintSettings } from '../lib/export-history.mjs';
import { packCore3mf } from '../public/core-3mf.js';
import { BoxGeometry } from '../public/vendor/three/three.module.js';

const palette=['#FF0000','#0000FF','#00FF00'];
const runs=ids=>ids.map((index,i)=>({from:i+1,to:i+1,colors:[palette[index]]}));
const items=[{height:20,layerHeight:.2,towerChannels:palette.slice(0,2)}];
const config={filament_colour:palette,filament_density:[1,2,3],flush_volumes_matrix:[0,100,200,300,0,400,500,600,0],flush_multiplier:.5,enable_prime_tower:false};
const forward=estimatePrintWaste(runs([0,1]),palette,config,items);
assert.equal(forward.flushMm3,50);assert.equal(forward.flushGrams,.1,'Incoming filament density applies');
assert.equal(forward.purgeAssumed,false);assert.equal(forward.towerGrams,0);
assert.equal(estimatePrintWaste(runs([1,0]),palette,config,items).flushMm3,150,'Flush matrix is directional');
assert.equal(estimatePrintWaste(runs([0,1]),palette,{...config,flush_multiplier:0},items).flushMm3,0);
assert.equal(estimatePrintWaste(runs([0,1]),palette,{...config,flush_volumes_matrix:Array(9).fill(0)},items).purgeAssumed,false,'A saved zero matrix is not missing');
const unknown=estimatePrintWaste(runs([0,1]),palette,{...config,flush_volumes_matrix:[]},items);
assert.equal(unknown.purgeAssumed,true);assert.equal(unknown.flushMm3,140);
const manual={...config,enable_prime_tower:true,filament_map_mode:'Manual',filament_map:[1,2,1]};
const dedicated=estimatePrintWaste(runs([0,1]),palette,manual,items);
assert.equal(dedicated.flushMm3,0);assert.equal(dedicated.nozzleChanges,1);assert.ok(dedicated.towerGrams>0,'A dedicated nozzle still requires priming and a tower');
const returning=estimatePrintWaste(runs([0,1,2,0]),palette,manual,items);
assert.equal(returning.flushMm3,350,'Returning to a nozzle flushes its resident color, not the previous active nozzle');
const sparseRuns=[{from:1,to:50,colors:[palette[0]]},{from:51,to:100,colors:[palette[1]]}];
const full=estimatePrintWaste(sparseRuns,palette,{...config,enable_prime_tower:true},items);
assert.equal(estimatePrintWaste(sparseRuns,palette,{...config,enable_prime_tower:true,prime_tower_width:'invalid'},items),null,'Invalid tower settings cannot silently report zero tower waste');
const skip=estimatePrintWaste(sparseRuns,palette,{...config,enable_prime_tower:true,wipe_tower_no_sparse_layers:true},items);
assert.ok(full.towerMm3>skip.towerMm3);
assert.ok(estimatePrintWaste(sparseRuns,palette,{...config,enable_prime_tower:true,prime_tower_brim_width:10},items).towerMm3>full.towerMm3);
const rectangular={...config,enable_prime_tower:true,prime_tower_rib_wall:false,prime_tower_fillet_wall:false,prime_tower_brim_width:0};
const reservation={...estimatePrimeTower(items,{config:rectangular},{runs:sparseRuns}),width:40,depth:20};
const sized=estimatePrintWaste(sparseRuns,palette,rectangular,items,reservation);
const wider=estimatePrintWaste(sparseRuns,palette,rectangular,items,{...reservation,width:80});
assert.ok(wider.towerGrams>sized.towerGrams,'Saved tower width changes material');
assert.equal(sized.tower.width,40);assert.equal(sized.tower.depth,20);assert.equal(sized.tower.shape,'rectangular');
assert.equal(sized.tower.printedLayers,51);assert.ok(Math.abs(sized.tower.height-10.2)<1e-8);
const stale=estimatePrintWaste(sparseRuns,palette,rectangular,items,{...reservation,height:20,lastChangeLayer:100,printedLayerCount:100});
assert.equal(stale.towerMm3,sized.towerMm3,'Stale reservations cannot override the exported layer plan');
const sharp=estimatePrintWaste(sparseRuns,palette,rectangular,items,reservation);
const rounded=estimatePrintWaste(sparseRuns,palette,{...rectangular,prime_tower_fillet_wall:true},items,reservation);
assert.ok(rounded.towerMm3<sharp.towerMm3,'Rounded corners change material');
const ribConfig={...rectangular,prime_tower_rib_wall:true,prime_tower_extra_rib_length:12};
const tapered=estimatePrintWaste(sparseRuns,palette,ribConfig,items,{...reservation,width:60,depth:60});
const untapered=estimatePrintWaste(sparseRuns,palette,{...ribConfig,prime_tower_extra_rib_length:0},items,{...reservation,width:60,depth:60});
assert.ok(tapered.towerMm3<untapered.towerMm3,'Tapered ribs reduce scaffold volume at the same footprint');
assert.equal(tapered.tower.extraRibLength,12);
assert.equal(skip.tower.printedLayers,2);assert.ok(Math.abs(skip.tower.height-.4)<1e-8);
assert.equal(forward.tower,null,'Disabled towers have no dimensions');
const geometry=new BoxGeometry(10,10,2).translate(0,0,1);
const template={config:{layer_height:'.2',nozzle_diameter:['.4']},filament:{filament_density:['1.24']},hotendCount:1};
const plate={id:'A',palette:palette.slice(0,2),objects:[{parts:[{geometry,materialIndex:0},{geometry,materialIndex:1}]}]};
const archive=packCore3mf({...plate,bambuTemplate:template});
const projectSettings=exportedPrintSettings(archive,['A']);
assert.deepEqual(projectSettings.A.flush_volumes_matrix,['0','300','300','0']);
const estimated=estimateFilament([plate],{printer:'p1s',nozzleDiameter:.4,settings:{}},template,{projectSettings});
assert.equal(estimated.purgeMm3PerChange,300,'Estimate uses the written 3MF matrix, not a template default');
assert.equal(estimated.version,4);assert.ok(estimated.primeTowerGrams>0);assert.equal(estimated.wasteGrams,estimated.flushGrams+estimated.primeTowerGrams);
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} != ${expected}`);
for(const waste of [forward,dedicated,returning,full,skip]) {
  near(waste.perColor.reduce((n,c)=>n+c.flushGrams,0),waste.flushGrams);
  near(waste.perColor.reduce((n,c)=>n+c.primeTowerGrams,0),waste.towerGrams);
}
assert.equal(forward.perColor.find(c=>c.color===palette[1]).flushGrams,.1);
const checkTotals=estimate=>{
  for(const key of ['modelGrams','flushGrams','primeTowerGrams','wasteGrams','totalGrams'])
    near(estimate.perColor.reduce((n,c)=>n+c[key],0),estimate[key]);
};
checkTotals(estimated);
assert.equal(estimated.primeTowers.length,1);assert.equal(estimated.primeTowers[0].plateId,'A');
near(estimated.primeTowers[0].grams,estimated.primeTowerGrams);
const multi=estimateFilament([plate,{...plate,id:'B',palette:[...plate.palette].reverse()}],{settings:{}},template);
checkTotals(multi);assert.equal(multi.perColor.length,2);
assert.deepEqual(multi.primeTowers.map(tower=>tower.plateId),['A','B']);
near(multi.primeTowers.reduce((sum,tower)=>sum+tower.grams,0),multi.primeTowerGrams);
const painted={...plate,objects:[{parts:[{geometry,materialIndex:0,materialIndices:Uint32Array.from({length:12},(_,i)=>i%2)}]}]};
const mixed=estimateFilament([painted],{settings:{}},{config:{...config,filament_colour:palette.slice(0,2)}});
checkTotals(mixed);near(mixed.perColor[1].modelGrams,2*mixed.perColor[0].modelGrams);
assert.ok(mixed.notes.some(note=>note.includes('colored surface area')));
const unavailable=estimateFilament([plate],{settings:{prime_tower_width:'invalid'}},template);
assert.equal(unavailable.totalGrams,null);assert.ok(unavailable.perColor.every(c=>c.totalGrams===null&&c.primeTowerGrams===null&&c.modelGrams>0));
assert.equal(estimated.totalGrams,estimated.modelGrams+estimated.wasteGrams);geometry.dispose();
console.log('Waste estimation passed: directional matrix, multiplier/zero handling, densities, resident nozzle colors, tower/brim/sparse layers and actual exported settings.');
